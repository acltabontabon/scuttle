/** Errors arrive as a tagged object, never as a stringified Rust type. */
export interface ScuttleError {
  code:
    | 'storage'
    | 'io'
    | 'serde'
    | 'not_found'
    | 'stale'
    | 'refused'
    | 'scan_busy'
    | 'busy'
    | 'transfer'
    | 'internal'
  message: string
  /** For `transfer`: what kind, in which phase, with which OS code. */
  failure?: {
    kind: FailureKind
    phase: FailurePhase
    os_code: number | null
    item: string
  }
}

export function isScuttleError(value: unknown): value is ScuttleError {
  return (
    typeof value === 'object' &&
    value !== null &&
    'code' in value &&
    'message' in value
  )
}
