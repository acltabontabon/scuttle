/** What went wrong, in terms of what a person could do about it. */
export type FailureKind =
  | 'stale'
  | 'replaced'
  | 'access_denied'
  | 'in_use'
  | 'missing'
  | 'collision'
  | 'no_space'
  | 'read_only'
  | 'path_too_long'
  | 'cross_volume_refused'
  | 'unsupported'
  | 'unsafe'
  | 'cancelled'
  | 'other'

export type NextStep = 'refresh' | 'retry' | 'free_space' | 'leave_alone' | 'close_app'

export type FailurePhase =
  | 'check'
  | 'snapshot'
  | 'prepare'
  | 'publish'
  | 'copy'
  | 'verify'
  | 'remove_source'
  | 'record'
  | 'restore'

/** One kind of failure, counted. Only file *names* are ever carried. */
export interface IssueGroup {
  kind: FailureKind
  phase: FailurePhase
  /** The code the operating system gave, kept exactly. */
  os_code: number | null
  count: number
  samples: string[]
  next_step: NextStep
  explanation: string
}

export type MovePhase =
  | 'checking'
  | 'moving'
  | 'finalizing'
  | 'completed'
  | 'partial'
  | 'failed'
  | 'cancelled'

export type FindingStatus = 'moved' | 'partial' | 'skipped' | 'failed'

export interface FindingResult {
  finding_id: string
  display_name: string
  category: Category | null
  /** What the counts are counts of: a folder's files, or one whole thing. */
  unit: 'files' | 'item'
  status: FindingStatus
  moved: number
  skipped: number
  failed: number
  moved_bytes: number
  record_id: string | null
  needs_refresh: boolean
  retryable: boolean
  issues: IssueGroup[]
  refusal: { code: string; message: string } | null
}

export interface MoveReport {
  outcome: MovePhase
  moved_files: number
  /** Bytes now in the drawer. Moved, not freed. */
  moved_bytes: number
  skipped: number
  failed: number
  remaining: number
  cancelled: boolean
  kept: string | null
  findings: FindingResult[]
  notice: string | null
}

/** One moment in a move. `job_id` and `rev` only ever rise. */
export interface MoveSnapshot {
  job_id: number
  rev: number
  phase: MovePhase
  cancelling: boolean
  /** Unknown (null) until Scuttle has finished checking. */
  total: number | null
  processed: number
  moved: number
  skipped: number
  failed: number
  moved_bytes: number
  /** Bytes actually copied across a drive. Zero for a rename. */
  copied_bytes: number
  label: string
  report: MoveReport | null
}

